// Writes the `_headers` file that Wrangler compiles into edge cache rules when
// the Worker is published.
//
// Without it every asset outside `/_next/static/*` goes out as
// `Cache-Control: public, max-age=0, must-revalidate`, so repeat visitors pull
// the whole data snapshot from the origin again.
import { access, mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import type { Plugin } from "vite";

const HEADERS_FILENAME = "_headers";

// vinext only emits its immutable rule when `_headers` does not exist yet, so a
// file written before it runs would silently drop that rule. The rule is
// repeated here for that reason; keep it in sync with `build.assetsDir`
// (default `_next/static`).
//
// This hook also runs before the client environment wipes its output directory
// (step 4 of the build), so an early write is thrown away — which is why the
// hook re-appends on every call instead of writing once.
//
// `/data/lol.<hash>.json` and `/data/wiki/<hash>/<key>.json` are what the client
// actually fetches: their paths change whenever the bytes do, so they can be
// cached indefinitely. `/data/meta.json` is the opposite on purpose — a fixed
// path holding just `meta` (a few hundred bytes) so external consumers like the
// shields.io patch badge have something stable to read; it gets a SHORT window
// because a deploy does not purge entries already cached.
//
// There is no rule for the plain `/data/lol.json` any more: the build drops that
// copy from the output (see `PUBLIC_COPY_FILENAME`), so it is not served. The
// complete snapshot travels with git under `data/releases/<version>/`.
//
// Fonts and icons are not content-hashed, so they get the same treatment with a
// longer window than the mutable data paths.
const RULES = `# Generated by build/asset-headers.ts. Do not edit; change the rules there.
/_next/static/*
  Cache-Control: public, max-age=31536000, immutable

/data/lol.*.json
  Cache-Control: public, max-age=31536000, immutable

/data/wiki/*
  Cache-Control: public, max-age=31536000, immutable

/data/meta.json
  Cache-Control: public, max-age=300, stale-while-revalidate=86400

/fonts/*
  Cache-Control: public, max-age=604800, stale-while-revalidate=86400

/favicon.svg
  Cache-Control: public, max-age=604800, stale-while-revalidate=86400
`;

async function exists(path: string): Promise<boolean> {
  try {
    await access(path);
    return true;
  } catch {
    return false;
  }
}

/** Writes the asset cache rules into the client build's `_headers` file. */
export function assetHeaders(): Plugin {
  let root = process.cwd();

  return {
    name: "lol-atlas-asset-headers",
    configResolved(config) {
      root = config.root;
    },
    async closeBundle() {
      const target = resolve(root, "dist", "client", HEADERS_FILENAME);
      // vinext runs several builds; the client output directory may not exist on
      // the first pass and may already carry content on a later one.
      await mkdir(dirname(target), { recursive: true });
      const current = (await exists(target)) ? await readFile(target, "utf8") : "";
      if (current.includes("Generated by build/asset-headers.ts")) return;
      const separator = current && !current.endsWith("\n") ? "\n\n" : current ? "\n" : "";
      await writeFile(target, `${current}${separator}${RULES}`, "utf8");
    },
  };
}
