// Writes the `_headers` file that Wrangler compiles into edge cache rules when
// the Worker is published.
//
// Without it every asset outside `/_next/static/*` goes out as
// `Cache-Control: public, max-age=0, must-revalidate`, so repeat visitors pull
// the whole data snapshot from the origin again.
import { access, mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import type { Plugin } from "vite";

const HEADERS_FILENAME = "_headers";

// vinext only emits its immutable rule when `_headers` does not exist yet, so
// writing this file first would silently drop it. The rule is repeated here for
// that reason; keep it in sync with `build.assetsDir` (default `_next/static`).
//
// `/data/lol.json` is ~3 MB and every page load fetches it. It is stable for the
// lifetime of a patch, so let the edge serve repeat visits. A deploy does not
// purge entries already cached, which is why max-age stays at an hour instead of
// going `immutable`: pipeline corrections within a patch still have to land.
//
// Fonts and icons are not content-hashed, so they get the same treatment with a
// longer window.
const RULES = `# Generated by build/asset-headers.ts. Do not edit; change the rules there.
/_next/static/*
  Cache-Control: public, max-age=31536000, immutable

/data/lol.json
  Cache-Control: public, max-age=3600, stale-while-revalidate=86400

/fonts/*
  Cache-Control: public, max-age=604800, stale-while-revalidate=86400

/favicon.svg
  Cache-Control: public, max-age=604800, stale-while-revalidate=86400
`;

async function exists(path: string): Promise<boolean> {
  try {
    await access(path);
    return true;
  } catch {
    return false;
  }
}

/** Writes the asset cache rules into the client build's `_headers` file. */
export function assetHeaders(): Plugin {
  let root = process.cwd();

  return {
    name: "lol-atlas-asset-headers",
    configResolved(config) {
      root = config.root;
    },
    async closeBundle() {
      const target = resolve(root, "dist", "client", HEADERS_FILENAME);
      // vinext runs several builds; the client output directory may not exist on
      // the first pass and may already carry content on a later one.
      await mkdir(dirname(target), { recursive: true });
      const current = (await exists(target)) ? await readFile(target, "utf8") : "";
      if (current.includes("Generated by build/asset-headers.ts")) return;
      const separator = current && !current.endsWith("\n") ? "\n\n" : current ? "\n" : "";
      await writeFile(target, `${current}${separator}${RULES}`, "utf8");
    },
  };
}
